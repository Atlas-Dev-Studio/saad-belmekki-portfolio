const langToggle = document.getElementById("lang-toggle");
const frLabel = langToggle.querySelector(".lang-fr");
const enLabel = langToggle.querySelector(".lang-en");

function applyLang(lang) {
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (translations[lang][key]) el.textContent = translations[lang][key];
  });
  frLabel.classList.toggle("active", lang === "fr");
  enLabel.classList.toggle("active", lang === "en");
  try { localStorage.setItem("lang", lang); } catch (e) {}
}

let currentLang = "fr";
try { currentLang = localStorage.getItem("lang") || "fr"; } catch (e) {}
applyLang(currentLang);

langToggle.addEventListener("click", () => {
  currentLang = currentLang === "fr" ? "en" : "fr";
  applyLang(currentLang);
});

// Mobile nav
const navToggle = document.getElementById("nav-toggle");
const mainNav = document.getElementById("main-nav");
navToggle.addEventListener("click", () => mainNav.classList.toggle("open"));
mainNav.querySelectorAll("a").forEach(a =>
  a.addEventListener("click", () => mainNav.classList.remove("open"))
);

// Scroll reveal
const revealEls = document.querySelectorAll(".reveal");
const observer = new IntersectionObserver(
  entries => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add("in-view");
        observer.unobserve(entry.target);
      }
    });
  },
  { threshold: 0.15 }
);
revealEls.forEach(el => observer.observe(el));

// Footer year
document.getElementById("year").textContent = new Date().getFullYear();
